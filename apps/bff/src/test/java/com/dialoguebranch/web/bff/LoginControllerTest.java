package com.dialoguebranch.web.bff;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.security.oauth2.client.OAuth2AuthorizedClientManager;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.redirectedUrl;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * {@link LoginController}: an unauthenticated request reaches it directly (no login redirect loop)
 * and it forwards to the actual OAuth2 authorization endpoint.
 */
@SpringBootTest
@AutoConfigureMockMvc
class LoginControllerTest {

	@Autowired
	MockMvc mockMvc;

	// Present so the context wires; this controller does not reach a component that uses it.
	@MockitoBean
	OAuth2AuthorizedClientManager authorizedClientManager;

	@Test
	void loginIsReachableWithoutASessionAndRedirectsToTheAuthorizationEndpoint() throws Exception {
		mockMvc.perform(get("/login"))
				.andExpect(status().isFound())
				.andExpect(redirectedUrl("/oauth2/authorization/keycloak"));
	}
}
